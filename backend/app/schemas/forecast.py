from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, model_validator
from app.schemas.market import DateRange


class ForecastRequest(BaseModel):
    dataset_name: Optional[str] = Field(None, description="Name of the CSV dataset in datasets/raw or datasets/processed")
    dataset: Optional[str] = Field(None, description="Alias for dataset_name")
    symbol: Optional[str] = Field(None, description="Alias for dataset_name")
    market_id: Optional[str] = Field(None, description="Alias for dataset_name")
    target_col: Optional[str] = Field(None, description="Target column to forecast (default is close or target_value)")
    target: Optional[str] = Field(None, description="Alias for target_col")
    horizon: int = Field(7, ge=1, le=60, description="Forecast horizon in days (1 to 60)")
    model_type: Optional[str] = Field(
        None,
        description="Model to use: 'baseline_naive', 'baseline_sma', 'linear_regression', 'ridge'",
    )
    model: Optional[str] = Field(None, description="Alias for model_type")
    model_id: Optional[str] = Field(None, description="Alias for model_type")
    sma_window: int = Field(5, ge=2, le=30, description="Window size for moving average baseline")

    @model_validator(mode="after")
    def apply_aliases(self):
        chosen_dataset = self.dataset_name or self.dataset or self.symbol or self.market_id
        if chosen_dataset is not None:
            self.dataset_name = chosen_dataset

        chosen_target = self.target_col or self.target
        if chosen_target is not None:
            self.target_col = chosen_target

        raw_model = self.model or self.model_id or self.model_type or "baseline_naive"
        chosen_model = str(raw_model).lower()
        model_alias = {
            "naive_baseline": "baseline_naive",
            "naive": "baseline_naive",
            "baseline": "baseline_naive",
            "baseline_sma": "baseline_sma",
            "sma": "baseline_sma",
            "linear_regression": "linear_regression",
            "linear": "linear_regression",
            "ridge": "ridge",
        }.get(chosen_model, chosen_model)
        self.model_type = model_alias
        self.model = model_alias
        self.model_id = model_alias
        return self


class ForecastPoint(BaseModel):
    step: int
    timestamp: str
    predicted_value: Optional[float] = None
    value: Optional[float] = None
    lower_bound: Optional[float] = None
    upper_bound: Optional[float] = None
    lower: Optional[float] = None
    upper: Optional[float] = None


class ForecastResponse(BaseModel):
    model_name: str
    model_version: str
    dataset_name: str
    dataset: Optional[str] = None
    symbol: Optional[str] = None
    target_col: str
    target: Optional[str] = None
    model: Optional[str] = None
    model_id: Optional[str] = None
    horizon: int
    is_synthetic: bool = False
    frequency: Optional[str] = None
    generated_at: Optional[str] = None
    last_historical_timestamp: Optional[str] = None
    last_historical_value: Optional[float] = None
    forecasts: List[ForecastPoint] = Field(default_factory=list)
    predictions: List[ForecastPoint] = Field(default_factory=list)
    evaluation: Optional[Dict[str, float]] = None
    training_context: Dict[str, Any] = Field(default_factory=dict)
    marketId: Optional[Any] = None
    modelName: Optional[str] = None
    modelVersion: Optional[str] = None
    createdAt: Optional[str] = None
    values: List[Dict[str, Any]] = Field(default_factory=list)
    data_is_synthetic: Optional[bool] = None
    disclaimer: str = (
        "Forecasts are generated by a numerical machine learning prototype for informational purposes only. "
        "Not financial or investment advice."
    )


class ModelMetadata(BaseModel):
    model_id: Optional[str] = None
    key: Optional[str] = None
    name: str
    model_type: Optional[str] = None
    type: Optional[str] = None
    version: Optional[str] = "1.0.0"
    readiness_status: Optional[str] = None
    status: Optional[str] = None
    description: str
    parameters: Dict[str, Any] = Field(default_factory=dict)


class ModelListResponse(BaseModel):
    total_models: int
    models: List[ModelMetadata] = Field(default_factory=list)


class EvaluationRequest(BaseModel):
    dataset_name: Optional[str] = Field(None, description="Dataset name to evaluate on")
    dataset: Optional[str] = Field(None, description="Alias for dataset_name")
    symbol: Optional[str] = Field(None, description="Alias for dataset_name")
    market_id: Optional[str] = Field(None, description="Alias for dataset_name")
    target_col: Optional[str] = Field(None, description="Target column")
    target: Optional[str] = Field(None, description="Alias for target_col")
    model_type: str = Field(
        "linear_regression",
        description="'baseline_naive', 'baseline_sma', 'linear_regression', 'ridge'",
    )
    model: Optional[str] = Field(None, description="Alias for model_type")
    model_id: Optional[str] = Field(None, description="Alias for model_type")
    start_date: Optional[str] = Field(None, description="Start date filter")
    end_date: Optional[str] = Field(None, description="End date filter")
    horizon: int = Field(1, ge=1, le=30, description="Forecast step horizon (default 1-step ahead walk-forward)")
    test_ratio: float = Field(0.2, gt=0.05, lt=0.5, description="Chronological test holdout ratio")
    sma_window: int = Field(5, ge=2, le=30, description="SMA window size")

    @model_validator(mode="after")
    def apply_aliases(self):
        chosen_dataset = self.dataset_name or self.dataset or self.symbol or self.market_id
        if chosen_dataset is not None:
            self.dataset_name = chosen_dataset

        chosen_target = self.target_col or self.target
        if chosen_target is not None:
            self.target_col = chosen_target

        chosen_model = (self.model or self.model_id or self.model_type or "linear_regression").lower()
        model_alias = {
            "naive_baseline": "baseline_naive",
            "naive": "baseline_naive",
            "baseline": "baseline_naive",
            "baseline_sma": "baseline_sma",
            "sma": "baseline_sma",
            "linear_regression": "linear_regression",
            "linear": "linear_regression",
            "ridge": "ridge",
        }.get(chosen_model, chosen_model)
        self.model_type = model_alias
        if self.model is not None:
            self.model = model_alias
        if self.model_id is not None:
            self.model_id = model_alias
        return self


